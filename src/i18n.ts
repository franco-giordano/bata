let locale: Locale = 'en';
export const getLocale = () => locale;

export function setLocale(value: Locale, persist=true) {
  locale=value;
  if(persist)try{localStorage.setItem(localeKey,value);}catch{/* Language switching still works without storage. */}
}
export function initializeLocale() {
  let saved: string | null = null;
  try{saved=localStorage.getItem(localeKey);}catch{/* Storage can be unavailable in private browser modes. */}
  setLocale(saved==='en'||saved==='es-AR'?saved:typeof navigator!=='undefined'&&navigator.language.toLowerCase().startsWith('es')?'es-AR':'en',false);
}

export function t(key: MessageKey, params: TranslationParams={}) {
  return dictionaries[locale][key].replace(/\{(\w+)\}/g,(_,name: string)=>{
    const value=params[name];
    // Instrument IDs remain stable in JSON; translate them when displaying a
    // message, so even a visible validation error can change language in place.
    if(name==='sound' && ['hihat','snare','kick','click'].includes(String(value)))return soundName(value as Sound);
    return value===undefined ? `{${name}}` : String(value);
  });
}
export function soundName(sound: Sound) { return dictionaries[locale][`instrument.${sound}`]; }
export function plural(one: MessageKey, other: MessageKey, count: number) {
  return new Intl.PluralRules(locale).select(count)==='one'?one:other;
}
export class LocalizedError extends Error {
  constructor(public key: MessageKey, public params: TranslationParams={}) {super(t(key,params));}
}
